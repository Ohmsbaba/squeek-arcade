export function textCols(text: string, gap = 1) {
  let cols = 0;
  for (const ch of text) cols += (GLYPHS[ch] ?? GLYPHS[" "])[0].length + gap;
  return Math.max(0, cols - gap);
}

/** Draws dot-matrix text onto a 2D canvas. */
export function drawDots(
  ctx: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  pitch: number,
  color: string,
  opts: { gap?: number; radius?: number; glow?: number } = {},
) {
  const r = (opts.radius ?? 0.42) * pitch;
  const gap = opts.gap ?? 1;
  ctx.fillStyle = color;
  if (opts.glow) {
    ctx.shadowColor = color;
    ctx.shadowBlur = opts.glow;
  }
  ctx.beginPath();
  let cx = x;
  for (const ch of text) {
    const g = GLYPHS[ch] ?? GLYPHS[" "];
    for (let row = 0; row < 7; row++) {
      for (let col = 0; col < g[row].length; col++) {
        if (g[row][col] === "1") {
          const px = cx + col * pitch + pitch / 2;
          const py = y + row * pitch + pitch / 2;
          ctx.moveTo(px + r, py);
          ctx.arc(px, py, r, 0, Math.PI * 2);
        }
      }
    }
    cx += (g[0].length + gap) * pitch;
  }
  ctx.fill();
  ctx.shadowBlur = 0;
}
